function GetWeaponHash(weaponName)
	weaponName = tonumber(weaponName)
	local weapons = ESX.GetWeaponList()
	
	for i = 1, #weapons, 1 do
		if weapons[i].hash == weaponName then
			return weapons[i], i
		end
	end
end

function LunchTimer()
	Citizen.CreateThread(function()
		while true do 
			Wait(60*1000)
			if IsTimeDead >= 1 then
				IsTimeDead = IsTimeDead-1
			else
				IsTimeFinish = true
				break
			end
		end
	end)
end

function RespawnPed(ped, spawn, bool)
	SetEntityCoordsNoOffset(ped, spawn.coords, false, false, false, true)
	NetworkResurrectLocalPlayer(spawn.coords, spawn.heading, true, false)
	SetPlayerInvincible(ped, false)
	if bool then
		TriggerEvent('playerSpawned', spawn)
	end
	ClearPedBloodDamage(ped)
end

