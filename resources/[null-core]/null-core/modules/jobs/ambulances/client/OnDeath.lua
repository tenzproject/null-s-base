-- Résout l'ID serveur du tueur en gérant: ped joueur direct, conducteur véhicule
-- (car kill), et explosions/projectiles (ped owner). Retourne "Inconnu" sinon.
function ResolveKillerServerId()
    local myPed = PlayerPedId()
    local src = GetPedSourceOfDeath(myPed)
    if src == 0 or src == myPed then return "Inconnu" end

    if IsEntityAPed(src) and IsPedAPlayer(src) then
        local pid = NetworkGetPlayerIndexFromPed(src)
        if pid ~= -1 then
            local sid = GetPlayerServerId(pid)
            if sid and sid ~= 0 then return sid end
        end
    end

    if IsEntityAVehicle(src) then
        local driver = GetPedInVehicleSeat(src, -1)
        if driver ~= 0 and IsPedAPlayer(driver) then
            local pid = NetworkGetPlayerIndexFromPed(driver)
            if pid ~= -1 then
                local sid = GetPlayerServerId(pid)
                if sid and sid ~= 0 then return sid end
            end
        end
    end

    local owner = NetworkGetEntityOwner(src)
    if owner ~= -1 then
        local sid = GetPlayerServerId(owner)
        if sid and sid ~= 0 and sid ~= GetPlayerServerId(PlayerId()) then return sid end
    end

    return "Inconnu"
end


